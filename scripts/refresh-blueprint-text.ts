import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { BlueprintTextDisplay } from "./blueprint-text";
import { approvedBlueprintTextCoverage, overlayApprovedBlueprintText, readApprovedBlueprintText } from "./approved-blueprint-text";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mapPath = path.join(root, "data/enrichment/blueprint-display-map.json");
const coveragePath = path.join(root, "data/enrichment/enrichment-coverage.json");
const capture = await readApprovedBlueprintText(root);
const original = JSON.parse(await readFile(mapPath, "utf8")) as Record<string, BlueprintTextDisplay>;
const updated = overlayApprovedBlueprintText(original, capture);
const coverage = JSON.parse(await readFile(coveragePath, "utf8")) as Record<string, unknown>;
coverage["blueprint-display-map"] = approvedBlueprintTextCoverage(updated);
await writeFile(mapPath, JSON.stringify(updated, null, 2) + "\n");
await writeFile(coveragePath, JSON.stringify(coverage, null, 2) + "\n");
console.log("138 owned Blueprint names/descriptions imported; display coverage 144/1198.");
